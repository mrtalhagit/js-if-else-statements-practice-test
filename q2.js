/*
 Q2. Positive, Negative or Zero
 Create a variable num. Print Positive if it is greater than 0, Negative if it is
less than 0, and Zero if it is 0.
 Test: 5 -> Positive, -3 -> Negative, 0 -> Zero.
*/


let num = 5;

if (num > 0) {
  console.log("Positive");
} else if (num < 0) {
  console.log("Negative");
} else {
  console.log("Zero");
}